import { useMemo } from 'react';
import { motion } from 'framer-motion';
import { 
  DollarSign, Download, CheckCircle2, TrendingDown, ArrowRight, ExternalLink, Sparkles
} from 'lucide-react';
import {
  Bar, BarChart, ResponsiveContainer, XAxis, YAxis, Tooltip, Legend, Cell
} from 'recharts';
